#!/usr/bin/env python
"""Intermediate-fusion variant of a calibrated junction scenario for the
fidelity comparison (ISPASS experiment 2).

Reads <base>.yaml, switches every perception block to the WorldFusion feature
backend and the edge to the WorldFusion manager (same AB3DMOT tracker and
linear predictor as the object-sharing arms), and writes <base>_wf.yaml and a
runner <base>_wf.py. test_runner selects the pair with `--baselines wf`.

    python scripts/ispass/gen_fidelity_wf_yaml.py openscenario_3_edge_late_fusion scp_edge_late_fusion
"""
import sys, os, re, yaml

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "ecav", "scenario_testing")
MODEL = {
    "hypes_yaml": "ecav/ml_manager/models/worldfusion_multiv2x_translaug_finetune/config.yaml",
    "checkpoint": "ecav/ml_manager/models/worldfusion_multiv2x_translaug_finetune/net_epoch27.pth",
}
# conflict point of both junction geometries (RSU masts 25 m either side, crossing lane y = 128)
ANCHOR = [-85.0, 128.0, 0.0, 0.0, 0.0, 0.0]


def perception_blocks(node):
    if isinstance(node, dict):
        for k, v in node.items():
            if k == "perception" and isinstance(v, dict) and "activate" in v:
                yield v
            else:
                yield from perception_blocks(v)
    elif isinstance(node, list):
        for v in node:
            yield from perception_blocks(v)


def main(bases):
    for base in bases:
        src = os.path.join(ROOT, "config_yaml", base + ".yaml")
        d = yaml.safe_load(open(src))
        d["scenario_name"] = base + "_wf"
        n = 0
        for p in perception_blocks(d):
            p["backend"] = "worldfusion"
            p["worldfusion_model"] = dict(MODEL)
            n += 1
        for edge in d["scenario"]["edge_list"]:
            edge["manager_type"] = "worldfusion"
            edge["worldfusion_model"] = dict(MODEL)
            edge["predictor_type"] = "linear"
            edge["world_anchor"] = list(ANCHOR)
        dst = os.path.join(ROOT, "config_yaml", base + "_wf.yaml")
        with open(dst, "w") as f:
            f.write(f"# Generated by scripts/ispass/gen_fidelity_wf_yaml.py from {base}.yaml. Do not edit.\n")
            yaml.safe_dump(d, f, sort_keys=False)
        py = open(os.path.join(ROOT, base + ".py")).read()
        py2, k = re.subn(r"SCENARIO_NAME = '%s'" % re.escape(base), "SCENARIO_NAME = '%s_wf'" % base, py)
        assert k == 1, "SCENARIO_NAME not found in the runner"
        open(os.path.join(ROOT, base + "_wf.py"), "w").write(py2)
        print(f"{base}_wf: {n} perception blocks switched, edge manager worldfusion, anchor {ANCHOR[:2]}")


if __name__ == "__main__":
    main(sys.argv[1:] or ["openscenario_3_edge_late_fusion", "scp_edge_late_fusion"])
