#!/usr/bin/env python
"""Intermediate-fusion variant of a calibrated junction scenario for the
fidelity comparison (ISPASS experiment 2).

Reads <base>.yaml, switches every perception block to the WorldFusion feature
backend and the edge to the WorldFusion manager (same AB3DMOT tracker and
linear predictor as the object-sharing arms), and writes <base>_wf.yaml and a
runner <base>_wf.py. test_runner selects the pair with `--baselines wf`.

    python scripts/ispass/gen_fidelity_wf_yaml.py openscenario_3_edge_late_fusion scp_edge_late_fusion

Variants for the detector diagnosis (2026-11-12), selected with `--baselines <suffix>`:
    --suffix wfz43e45 --rsu-z 4.3 --epoch 45      mast height and checkpoint epoch
    --rsus "-82,128,4.3"                          replace the RSU list (first entries, extras dropped)
    --score 0.2                                   score threshold override
"""
import sys, os, re, yaml, argparse, copy

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "ecav", "scenario_testing")
MODEL = {
    "hypes_yaml": "ecav/ml_manager/models/worldfusion_multiv2x_translaug_finetune/config.yaml",
    "checkpoint": "ecav/ml_manager/models/worldfusion_multiv2x_translaug_finetune/net_epoch27.pth",
}
# conflict point of both junction geometries (RSU masts 25 m either side, crossing lane y = 128)
ANCHOR = [-85.0, 128.0, 0.0, 0.0, 0.0, 0.0]


def perception_blocks(node):
    if isinstance(node, dict):
        for k, v in node.items():
            if k == "perception" and isinstance(v, dict) and "activate" in v:
                yield v
            else:
                yield from perception_blocks(v)
    elif isinstance(node, list):
        for v in node:
            yield from perception_blocks(v)


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("bases", nargs="*", default=["openscenario_3_edge_late_fusion", "scp_edge_late_fusion"])
    ap.add_argument("--suffix", default="wf")
    ap.add_argument("--epoch", type=int, default=27)
    ap.add_argument("--rsu-z", type=float, default=None)
    ap.add_argument("--rsus", default=None)
    ap.add_argument("--score", type=float, default=None)
    a = ap.parse_args(argv)
    model = dict(MODEL)
    model["checkpoint"] = re.sub(r"net_epoch\d+", f"net_epoch{a.epoch}", model["checkpoint"])
    if a.score is not None:
        model["score_threshold"] = a.score
    for base in a.bases:
        src = os.path.join(ROOT, "config_yaml", base + ".yaml")
        d = yaml.safe_load(open(src))
        name = f"{base}_{a.suffix}"
        d["scenario_name"] = name
        n = 0
        for p in perception_blocks(d):
            p["backend"] = "worldfusion"
            p["worldfusion_model"] = dict(model)
            n += 1
        for edge in d["scenario"]["edge_list"]:
            edge["manager_type"] = "worldfusion"
            edge["worldfusion_model"] = dict(model)
            edge["predictor_type"] = "linear"
            edge["world_anchor"] = list(ANCHOR)
            if a.rsus:
                pos = [[float(v) for v in r.split(",")] for r in a.rsus.split(";")]
                edge["rsus"] = [copy.deepcopy(r) for r in edge["rsus"][:len(pos)]]
                for r, xyz in zip(edge["rsus"], pos):
                    r["spawn_position"] = xyz
            if a.rsu_z is not None:
                for r in edge["rsus"]:
                    r["spawn_position"][2] = a.rsu_z
        dst = os.path.join(ROOT, "config_yaml", name + ".yaml")
        with open(dst, "w") as f:
            f.write(f"# Generated by scripts/ispass/gen_fidelity_wf_yaml.py from {base}.yaml "
                    f"({' '.join(argv)}). Do not edit.\n")
            yaml.safe_dump(d, f, sort_keys=False)
        py = open(os.path.join(ROOT, base + ".py")).read()
        py2, k = re.subn(r"SCENARIO_NAME = '%s'" % re.escape(base), "SCENARIO_NAME = '%s'" % name, py)
        assert k == 1, "SCENARIO_NAME not found in the runner"
        open(os.path.join(ROOT, name + ".py"), "w").write(py2)
        print(f"{name}: {n} perception blocks switched, epoch {a.epoch}, "
              f"rsus {[r['spawn_position'] for e in d['scenario']['edge_list'] for r in e['rsus']]}")


if __name__ == "__main__":
    main(sys.argv[1:])
