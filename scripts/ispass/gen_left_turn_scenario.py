#!/usr/bin/env python
"""Generate ltp_column: one sensor-equipped vehicle turns left at the junction of the straight crossing.

    python scripts/ispass/gen_left_turn_scenario.py      # writes ltp_column.yaml and ltp_column.py

The base is scp_column (scripts/ispass/gen_column_scenario.py) with the destination of the left turn
(openscenario_3_edge_late_fusion): the vehicle approaches on the same lane, turns left inside the junction
and crosses the lane of the crossing car. Sensors, tracker, predictor and planner are those of scp_column,
and the scenario logic is scp_edge_late_fusion (crossing car launched in simulation time).
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CFG = os.path.join(ROOT, "ecav", "scenario_testing", "config_yaml"); MOD = os.path.join(ROOT, "ecav", "scenario_testing")
STRAIGHT = "destination: [-85.1, 155.0, 0.5]"; LEFT = "destination: [-28.8, 134.7, 0.5]"


def main():
    y = open(os.path.join(CFG, "scp_column.yaml")).read()
    assert y.count(STRAIGHT) == 1 and y.count("scenario_name: scp_column") == 1
    y = y.replace(STRAIGHT, LEFT).replace("scenario_name: scp_column", "scenario_name: ltp_column")
    open(os.path.join(CFG, "ltp_column.yaml"), "w").write(
        "# Generated by scripts/ispass/gen_left_turn_scenario.py from scp_column.yaml; do not edit.\n" + y)
    open(os.path.join(MOD, "ltp_column.py"), "w").write(
        '# -*- coding: utf-8 -*-\n"""One sensor-equipped vehicle on the left turn. Generated by\n'
        'scripts/ispass/gen_left_turn_scenario.py; the scenario logic is scp_edge_late_fusion."""\n'
        "from ecav.scenario_testing.scp_edge_late_fusion import *  # noqa: F401,F403\n"
        "from ecav.scenario_testing.scp_edge_late_fusion import run_scenario, run_vehicle, exec_scenario_runner  # noqa: F401\n")
    print("wrote ltp_column.yaml and ltp_column.py")


if __name__ == "__main__":
    main()
