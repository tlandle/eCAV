"""Multi-V2X cooperative motion prediction dataset for MTR (CMP-style).

Each training record is one (scenario, rsu, timestamp). The RSU is the
zone anchor; gt/pred trajectories come from the preprocessed pickles
generated by export_wf_for_mtr.py, in world (CARLA) frame.
WorldFusion's fused BEV feature is loaded per (scenario, rsu, ts) from
the .npy cache, and the per-zone lane raster PNG provides the Swin
lane-encoder input.

Inputs come from one directory layout (the export script's output):
  <root>/
    manifest.json
    rsu_poses.json
    multiv2x_cluster_64_center_dict.pkl
    multiv2x_gt_traj/{train,test}/<scen>-<rsu>-traj.pickle
    multiv2x_pred_traj/{train,test}/<scen>-<rsu>-traj.pickle
    wf_fused_features/{train,test}/wf_fused_<scen>_<rsu>_<ts>.npy
    lane_maps/<scen>_<rsu>.png

The trajectory pickle schema is:
  {'data': {object_id: [state_t, ...]}, 'timestamps': [str]}
  state_t = [x, y, z, l, w, h, yaw_deg, valid]
"""

from __future__ import annotations

import json
import logging
import os
import pickle
from collections import OrderedDict
from typing import Dict, List, Tuple

import numpy as np
import torch
from PIL import Image

from mtr.datasets.dataset import DatasetTemplate
from mtr.utils import common_utils


logger_default = logging.getLogger(__name__)


class MultiV2XMultiEgoDataset(DatasetTemplate):
    """Multi-V2X dataset for CMP-style MTR training on WorldFusion features."""

    def __init__(self, dataset_cfg, training=True, logger=None, visualize=False):
        super().__init__(dataset_cfg=dataset_cfg, training=training, logger=logger)
        self.is_train = training
        self.logger = logger or logger_default

        cfg = dataset_cfg
        self.root_dir = cfg['root_dir']
        self.split = 'train' if training else 'test'

        self.past_frames = cfg.get('PAST_FRAMES', 10)
        self.future_frames = cfg.get('FUTURE_FRAMES', 25)
        self.max_objects = cfg.get('MAX_OBJECTS', 64)

        # Paths derived from root
        self.gt_traj_dir = os.path.join(
            self.root_dir, 'multiv2x_gt_traj', self.split)
        self.pred_traj_dir = os.path.join(
            self.root_dir, 'multiv2x_pred_traj', self.split)
        self.feat_dir = os.path.join(
            self.root_dir, 'wf_fused_features', self.split)
        self.lane_dir = os.path.join(self.root_dir, 'lane_maps')

        manifest_path = os.path.join(self.root_dir, 'dataset_info.json')
        with open(manifest_path) as f:
            info = json.load(f)
        records_info = [r for r in info['records'] if r['split'] == self.split]

        with open(os.path.join(self.root_dir, 'rsu_poses.json')) as f:
            self.rsu_poses = json.load(f)

        sample_interval = cfg.get('SAMPLE_INTERVAL', {'train': 1, 'test': 1})
        self.sample_interval = sample_interval.get(self.split, 1)

        # Build records: one record per (scenario, rsu, timestamp_idx) where
        # we have at least past_frames + future_frames context.
        self.records: List[Tuple[str, str, int, List[str]]] = []
        self.zone_traj_cache: Dict[Tuple[str, str], dict] = {}

        win = self.past_frames + self.future_frames + 1
        skipped = 0
        for r in records_info:
            scen, rsu = r['scenario'], r['rsu']
            gt_pkl = os.path.join(self.gt_traj_dir,
                                  f'{scen}-{rsu}-traj.pickle')
            pred_pkl = os.path.join(self.pred_traj_dir,
                                    f'{scen}-{rsu}-traj.pickle')
            if not (os.path.exists(gt_pkl) and os.path.exists(pred_pkl)):
                skipped += 1
                continue
            with open(gt_pkl, 'rb') as f:
                gt_obj = pickle.load(f)
            with open(pred_pkl, 'rb') as f:
                pr_obj = pickle.load(f)

            # Common timestamps (gt and pred must share order)
            ts_list = gt_obj['timestamps']
            if pr_obj['timestamps'] != ts_list:
                # Align: intersect and reindex.
                common = [t for t in ts_list if t in set(pr_obj['timestamps'])]
                ts_list = common
            if len(ts_list) < win:
                skipped += 1
                continue

            self.zone_traj_cache[(scen, rsu)] = {
                'timestamps': ts_list,
                'gt_data': gt_obj['data'],
                'pred_data': pr_obj['data'],
            }

            for t_idx in range(self.past_frames,
                               len(ts_list) - self.future_frames,
                               self.sample_interval):
                self.records.append((scen, rsu, t_idx, ts_list))

        if self.logger:
            self.logger.info(
                f'[MultiV2X-MTR {self.split}] {len(self.records)} records '
                f'across {len(self.zone_traj_cache)} zones '
                f'({skipped} zones skipped for missing/insufficient data)')

    def __len__(self):
        return len(self.records)

    # ----------------------------------------------------------------- helpers

    def _zone_data(self, scen, rsu):
        return self.zone_traj_cache[(scen, rsu)]

    def _load_fused_feature(self, scen, rsu, ts):
        path = os.path.join(self.feat_dir, f'wf_fused_{scen}_{rsu}_{ts}.npy')
        # Stored as float16, [1, C, H, W]; consumer casts as needed
        return np.load(path)

    def _load_lane_image(self, scen, rsu):
        path = os.path.join(self.lane_dir, f'{scen}_{rsu}.png')
        img = Image.open(path)
        if img.mode != 'RGB':
            img = img.convert('RGB')
        return np.array(img, dtype=np.uint8)  # (H, W, 3)

    def _rsu_pose(self, scen, rsu):
        return self.rsu_poses[scen][rsu]

    # ----------------------------------------------------------------- core

    def __getitem__(self, index):
        scen, rsu, t_idx, ts_list = self.records[index]
        zd = self._zone_data(scen, rsu)
        gt_data, pred_data = zd['gt_data'], zd['pred_data']

        past_ts = ts_list[t_idx - self.past_frames: t_idx + 1]
        future_ts = ts_list[t_idx + 1: t_idx + 1 + self.future_frames]
        cur_ts = ts_list[t_idx]
        n_past, n_future = len(past_ts), len(future_ts)

        # Build per-object past/future arrays.
        # Past: use pred_data (perception+tracking trajectories).
        # Future: use gt_data (ground-truth supervision).
        # Center objects: vehicles visible at the current timestamp in pred.
        obj_ids = []
        for oid, seq in pred_data.items():
            cur = seq[ts_list.index(cur_ts)] if t_idx < len(seq) else None
            if cur is not None and cur[7] == 1:
                obj_ids.append(oid)
        if not obj_ids:
            # Fall back to GT visibility (zone has no pred detections at this t)
            for oid, seq in gt_data.items():
                if t_idx < len(seq) and seq[t_idx][7] == 1:
                    obj_ids.append(oid)
        if not obj_ids:
            return self.__getitem__((index + 1) % len(self))

        obj_ids = obj_ids[: self.max_objects]
        N = len(obj_ids)

        # Trajectory tensors: [x, y, z, l, w, h, heading_rad, valid]
        obj_trajs_past = np.zeros((N, n_past, 8), dtype=np.float32)
        obj_trajs_future = np.zeros((N, n_future, 8), dtype=np.float32)

        for i, oid in enumerate(obj_ids):
            pred_seq = pred_data.get(oid)
            gt_seq = gt_data.get(oid)
            for j, ts in enumerate(past_ts):
                if pred_seq is None:
                    continue
                k = t_idx - self.past_frames + j
                if 0 <= k < len(pred_seq):
                    s = pred_seq[k]
                    if s[7] == 1:
                        obj_trajs_past[i, j] = [
                            s[0], s[1], s[2], s[3], s[4], s[5],
                            np.deg2rad(s[6]), 1.0]
            for j, ts in enumerate(future_ts):
                if gt_seq is None:
                    continue
                k = t_idx + 1 + j
                if 0 <= k < len(gt_seq):
                    s = gt_seq[k]
                    if s[7] == 1:
                        obj_trajs_future[i, j] = [
                            s[0], s[1], s[2], s[3], s[4], s[5],
                            np.deg2rad(s[6]), 1.0]

        # Center objects: state at the current timestamp (last past frame)
        center_objects = obj_trajs_past[:, -1, :].copy()
        valid_mask = center_objects[:, 7] > 0
        if not valid_mask.any():
            return self.__getitem__((index + 1) % len(self))
        # Keep only objects with valid current pose
        obj_trajs_past = obj_trajs_past[valid_mask]
        obj_trajs_future = obj_trajs_future[valid_mask]
        center_objects = center_objects[valid_mask]
        obj_ids = [obj_ids[i] for i, v in enumerate(valid_mask) if v]
        N = center_objects.shape[0]
        track_index_to_predict = np.arange(N)
        obj_types = np.array(['TYPE_VEHICLE'] * N)
        obj_ids_arr = np.array(obj_ids)

        (obj_trajs_data, obj_trajs_mask, obj_trajs_pos, obj_trajs_last_pos,
         obj_trajs_future_state, obj_trajs_future_mask,
         center_gt_trajs, center_gt_trajs_mask, center_gt_final_valid_idx,
         track_index_to_predict_new, _sdc,
         obj_types, obj_ids_arr) = self._create_agent_data_for_center_objects(
            center_objects=center_objects,
            obj_trajs_past=obj_trajs_past,
            obj_trajs_future=obj_trajs_future,
            track_index_to_predict=track_index_to_predict,
            obj_types=obj_types,
            obj_ids=obj_ids_arr,
        )

        obj_trajs_full = np.concatenate([obj_trajs_past, obj_trajs_future], axis=1)

        # Lane raster (broadcast to per-center)
        lane = self._load_lane_image(scen, rsu)  # (H, W, 3) uint8
        lane = np.expand_dims(lane, axis=0)
        lane = np.repeat(lane, center_objects.shape[0], axis=0)

        # WF fused feature for the current timestamp
        fused_feature = self._load_fused_feature(scen, rsu, cur_ts)

        ret = {
            'scenario_id': np.array([f'{scen}/{rsu}/{cur_ts}'] * N),
            'scenario_name': np.array([scen] * N),
            'timestamp_idx': np.array([t_idx] * N),
            'timestamp_key': np.array([cur_ts] * N),
            'ego_cav_id': np.array([rsu] * N),

            'obj_trajs': obj_trajs_data,
            'obj_trajs_mask': obj_trajs_mask,
            'map_polylines': lane,  # Swin lane encoder input
            'track_index_to_predict': track_index_to_predict_new,
            'obj_trajs_pos': obj_trajs_pos,
            'obj_trajs_last_pos': obj_trajs_last_pos,
            'obj_types': obj_types,
            'obj_ids': obj_ids_arr,

            'center_objects_world': center_objects,
            'center_objects_id': obj_ids_arr[track_index_to_predict_new],
            'center_objects_type': obj_types[track_index_to_predict_new],

            'obj_trajs_future_state': obj_trajs_future_state,
            'obj_trajs_future_mask': obj_trajs_future_mask,
            'center_gt_trajs': center_gt_trajs,
            'center_gt_trajs_mask': center_gt_trajs_mask,
            'center_gt_final_valid_idx': center_gt_final_valid_idx,
            'center_gt_trajs_src': obj_trajs_full[track_index_to_predict_new],

            'fused_feature': fused_feature,
        }
        return ret

    # ---------------------------------------------------------------- collate

    def collate_batch(self, batch_list):
        # Matches the OPV2V multiego MTR collate: per-scene packing, one
        # scene per "batch" (the MTR train loop multiplies via gradient acc).
        cavs_data_for_mtr = batch_list  # list, len=N_centers in scene

        if len(cavs_data_for_mtr) == 0:
            return {'num_cavs': 0, 'input_dict': {}, 'batch_sample_count': []}

        key_to_list = {}
        for key in cavs_data_for_mtr[0].keys():
            key_to_list[key] = [d[key] for d in cavs_data_for_mtr]

        input_dict = {}
        tensor_keys_to_merge = [
            'obj_trajs', 'obj_trajs_mask',
            'map_polylines', 'map_polylines_mask', 'map_polylines_center',
            'obj_trajs_pos', 'obj_trajs_last_pos',
            'obj_trajs_future_state', 'obj_trajs_future_mask',
        ]
        for key, val_list in key_to_list.items():
            if key in tensor_keys_to_merge and val_list[0] is not None:
                val_list_t = [torch.from_numpy(v) for v in val_list]
                input_dict[key] = common_utils.merge_batch_by_padding_2nd_dim(val_list_t)
            elif key in ('scenario_id', 'scenario_name', 'timestamp_idx',
                         'timestamp_key', 'ego_cav_id',
                         'obj_types', 'obj_ids',
                         'center_objects_type', 'center_objects_id'):
                input_dict[key] = np.concatenate(val_list, axis=0)
            elif key == 'fused_feature':
                input_dict[key] = [torch.from_numpy(v.astype(np.float32))
                                   for v in val_list]
            else:
                val_list_t = [torch.from_numpy(v) for v in val_list]
                input_dict[key] = torch.cat(val_list_t, dim=0)

        batch_sample_count = [len(x['track_index_to_predict'])
                              for x in cavs_data_for_mtr]
        return {
            'num_cavs': len(cavs_data_for_mtr),
            'input_dict': input_dict,
            'batch_sample_count': batch_sample_count,
        }

    # --------------------------------------------------------------- internal

    @staticmethod
    def _create_agent_data_for_center_objects(
            center_objects, obj_trajs_past, obj_trajs_future,
            track_index_to_predict, obj_types, obj_ids):
        """Normalize trajectories to each center object's frame."""
        num_center = center_objects.shape[0]
        num_past = obj_trajs_past.shape[1]

        obj_trajs_full = np.concatenate([obj_trajs_past, obj_trajs_future], axis=1)
        obj_trajs_mask = obj_trajs_full[:, :num_past, -1].astype(bool)
        obj_trajs_future_mask = obj_trajs_full[:, num_past:, -1].astype(bool)

        obj_trajs_torch = torch.tensor(obj_trajs_full).float()
        center_xyz = torch.tensor(center_objects[:, :3]).float()
        center_heading = torch.tensor(center_objects[:, 6]).float()

        obj_trajs_centered = MultiV2XMultiEgoDataset.transform_trajs_to_center_coords(
            obj_trajs_torch.unsqueeze(0).expand(num_center, -1, -1, -1).clone(),
            center_xyz, center_heading, heading_index=6,
        )

        obj_trajs_data = obj_trajs_centered[:, :, :num_past, :].numpy()
        obj_trajs_future_state = obj_trajs_centered[:, :, num_past:, :].numpy()
        obj_trajs_pos = obj_trajs_data[:, :, :, :2]
        obj_trajs_last_pos = obj_trajs_data[:, :, -1, :2]

        center_gt_trajs = obj_trajs_future_state[
            np.arange(num_center), track_index_to_predict, :, :2]
        center_gt_trajs_mask = obj_trajs_future_mask[track_index_to_predict]
        center_gt_final_valid_idx = np.array([
            np.where(center_gt_trajs_mask[i])[0][-1]
            if center_gt_trajs_mask[i].any() else 0
            for i in range(num_center)
        ])
        track_index_to_predict_new = np.arange(num_center)
        sdc_track_index_new = 0
        return (obj_trajs_data, obj_trajs_mask, obj_trajs_pos, obj_trajs_last_pos,
                obj_trajs_future_state, obj_trajs_future_mask,
                center_gt_trajs, center_gt_trajs_mask, center_gt_final_valid_idx,
                track_index_to_predict_new, sdc_track_index_new,
                obj_types, obj_ids)

    @staticmethod
    def transform_trajs_to_center_coords(obj_trajs, center_xyz, center_heading,
                                          heading_index):
        num_center = center_xyz.shape[0]
        obj_trajs[:, :, :, 0:center_xyz.shape[1]] -= center_xyz[:, None, None, :]
        obj_trajs[:, :, :, 0:2] = common_utils.rotate_points_along_z(
            points=obj_trajs[:, :, :, 0:2].reshape(num_center, -1, 2),
            angle=-center_heading,
        ).reshape(obj_trajs.shape[0], obj_trajs.shape[1],
                  obj_trajs.shape[2], 2)
        obj_trajs[:, :, :, heading_index] -= center_heading[:, None, None]
        return obj_trajs
